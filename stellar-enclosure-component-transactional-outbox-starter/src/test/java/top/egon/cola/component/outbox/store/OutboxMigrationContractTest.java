package top.egon.cola.component.outbox.store;

import org.junit.jupiter.api.Test;
import org.springframework.core.io.ClassPathResource;

import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.util.HexFormat;
import java.util.Locale;

import static org.assertj.core.api.Assertions.assertThat;

class OutboxMigrationContractTest {

    @Test
    void shouldPackageOneNonAutomaticPostgresqlMigrationTemplate() throws Exception {
        ClassPathResource resource = new ClassPathResource(
                "db/transactional-outbox/postgresql/V1__create_transactional_outbox_schema.sql");
        String sql = resource.getContentAsString(StandardCharsets.UTF_8);

        assertThat(resource.exists()).isTrue();
        assertThat(sql)
                .contains("create table egon_cola_outbox_message")
                .contains("uk_outbox_message_id")
                .contains("uk_outbox_idempotency_key")
                .contains("idx_outbox_claim")
                .contains("idx_outbox_reclaim")
                .contains("idx_outbox_cleanup");
        assertThat(new ClassPathResource("db/migration/V1__create_transactional_outbox_schema.sql").exists())
                .isFalse();
    }

    @Test
    void packagesAdditiveJdbcAndManagedMpCoordinationMigrations() throws Exception {
        String jdbcPath = "db/transactional-outbox/postgresql/V2__add_outbox_queue_coordination.sql";
        String mpPath = "db/egon-outbox-mp/V20261122_001__add_outbox_queue_coordination.sql";
        for (String path : new String[]{jdbcPath, mpPath}) {
            ClassPathResource resource = new ClassPathResource(path);
            assertThat(resource.exists()).as("coordination migration %s", path).isTrue();
            String sql = resource.getContentAsString(StandardCharsets.UTF_8)
                    .toLowerCase(Locale.ROOT).replaceAll("\\s+", " ");

            assertThat(sql).contains("create table egon_cola_outbox_queue_member",
                    "create table egon_cola_outbox_queue_lease", "shard_slot", "instance_id",
                    "capabilities_json", "last_seen_at", "owner_instance_id", "epoch", "expires_at",
                    "uk_outbox_queue_member_slot_instance", "uk_outbox_queue_lease_slot_channel");
            assertThat(sql).containsPattern("unique\\s*(?:index\\s+uk_outbox_queue_member_slot_instance\\s+on\\s+egon_cola_outbox_queue_member\\s*)?\\(shard_slot,\\s*instance_id\\)");
            assertThat(sql).containsPattern("unique\\s*(?:index\\s+uk_outbox_queue_lease_slot_channel\\s+on\\s+egon_cola_outbox_queue_lease\\s*)?\\(shard_slot,\\s*channel\\)");
            assertThat(sql).containsPattern("check\\s*\\(epoch\\s*>\\s*0\\)");
            assertThat(sql).doesNotContain("alter table egon_cola_outbox_message", "drop table",
                    "delete from", "update egon_cola_outbox_message", "references ",
                    "idx_outbox_queue_member_expiry");
        }

        String jdbc = new ClassPathResource(jdbcPath).getContentAsString(StandardCharsets.UTF_8)
                .toLowerCase(Locale.ROOT).replaceAll("\\s+", " ");
        assertThat(jdbc).contains("generated by default as identity");
        String mp = new ClassPathResource(mpPath).getContentAsString(StandardCharsets.UTF_8)
                .toLowerCase(Locale.ROOT).replaceAll("\\s+", " ");
        assertThat(mp).contains("tenant_id", "deleted_at", "version", "create_time", "update_time")
                .doesNotContain("generated by default as identity");
        assertThat(new ClassPathResource("db/migration/V2__add_outbox_queue_coordination.sql").exists())
                .isFalse();
    }

    @Test
    void previouslyPublishedMigrationBytesRemainImmutable() throws Exception {
        assertChecksum("db/transactional-outbox/postgresql/V1__create_transactional_outbox_schema.sql",
                "611d47e890618364c6c89d2967c4159ba5bde02756c52165799a6d6a0ca6b7f8");
        assertChecksum("db/egon-outbox-mp/V20260924_001__initialize_outbox_mp_schema.sql",
                "2bae1d8a90cdc7bd5a2c0889ff73625593de2d5b5261f60e23c3b8d76e708902");
        assertChecksum("db/egon-outbox-mp/V20261027_001__add_outbox_shard_slot.sql",
                "e05b26eca0b5d91f672441da2eaeaa7071787d3d5e910237e1832c3004706450");
    }

    private static void assertChecksum(String path, String expected) throws Exception {
        byte[] bytes = new ClassPathResource(path).getContentAsByteArray();
        assertThat(HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(bytes)))
                .as("published migration %s", path).isEqualTo(expected);
    }
}
